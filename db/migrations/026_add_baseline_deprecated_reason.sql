-- 口径版本的作废原因（2026-08-14）。
--
-- 迁移 024 建了"改口径就新写一版、旧行永不改写"的机制，但漏了一件事：**旧版本为什么作废、
-- 错在哪、错多少，没有地方写**。只标一个 deprecated 是不够的——将来有人翻到旧版本的数字，
-- 需要立刻知道该不该信它、差多少，否则只会卡在"这一天为什么对不上"。
--
-- 第一个用到它的就是 b9645fa10：定型检查逐小时 break、写库却按整天写，导致**每个窗口的
-- 最后一天只用了当天前若干小时的样本，而且从此不再重算**（storedDays 认为这天已经有了）。
-- 实测窗口 7 天的 2026-08-06 只有 14 小时样本（4550/325，完整应为 24 小时），
-- 中位数 -2.14%，完整重算是 -2.38%。八个窗口各一天，858 行里 8 行。
-- 量级不影响任何已有结论（判据是 6.7%~12% 的成本线），但混着两种口径的行会让将来的
-- 任何复核都先卡在对不上账，所以按护栏 (b) 新开一版整体重算、存量行一行不动。
ALTER TABLE market_baseline_meta ADD COLUMN deprecated_reason TEXT;
ALTER TABLE market_baseline_meta ADD COLUMN deprecated_at TEXT;

UPDATE market_baseline_meta
SET deprecated_reason =
      '边界日半天数据：定型检查逐小时 break、写库却按整天写，导致每个窗口最后一天只用了当天前若干小时的样本且从此不再重算。' ||
      '实测窗口 7 天的 2026-08-06 只有 14 小时（4550/325，完整应为 24 小时），中位数 -2.14% 而完整重算是 -2.38%。' ||
      '八个窗口各有一天受影响（858 行里 8 行）。量级不影响任何已有结论（判据是 6.7%~12% 的成本线），' ||
      '但混着两种口径会让将来的复核先卡在对不上账。继任版本：b03672dc0（口径加 dayCompleteness=whole-day-only）。',
    deprecated_at = '2026-08-14T07:30:00Z'
WHERE calc_version = 'b9645fa10';
